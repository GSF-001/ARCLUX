const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DOCS_OUT = path.join(ROOT, 'docs-site');
const GITHUB_BASE = 'https://github.com/GSF-001/ARCLUX/blob/main/';

function readIfExists(relPath) {
  const p = path.join(ROOT, relPath);
  if (fs.existsSync(p)) return fs.readFileSync(p, 'utf-8');
  return null;
}

function stripFrontmatter(content) {
  return content.replace(/^---[\s\S]*?---\n/, '');
}

// Bulldozer MDX-safe: escape semua "<" di luar fenced code block / autolink / comment,
// biar gak pernah dibaca sebagai JSX tag apapun isinya.
function mdxSafe(text) {
  const fenceBlocks = [];
  let out = text.replace(/```[\s\S]*?```/g, (m) => {
    fenceBlocks.push(m);
    return `\u0000FENCE${fenceBlocks.length - 1}\u0000`;
  });

  const autolinks = [];
  out = out.replace(/<(https?:\/\/[^\s<>]+|mailto:[^\s<>]+)>/g, (m) => {
    autolinks.push(m);
    return `\u0000AUTOLINK${autolinks.length - 1}\u0000`;
  });

  out = out.replace(/<!--/g, '\u0000CMTOPEN\u0000').replace(/-->/g, '\u0000CMTCLOSE\u0000');

  // Proteksi tag komponen Mintlify: <Card ...>, </Card>, <CardGroup cols={2}>, <Tabs>, dll.
  // Konvensi Mintlify: nama komponen selalu diawali huruf kapital.
  const jsxTags = [];
  out = out.replace(/<\/?[A-Z][A-Za-z0-9]*(?:\s+[^<>]*)?\/?>/g, (m) => {
    jsxTags.push(m);
    return `\u0000JSX${jsxTags.length - 1}\u0000`;
  });

  out = out.replace(/</g, '&lt;');

  out = out.replace(/\u0000JSX(\d+)\u0000/g, (m, i) => jsxTags[Number(i)]);
  out = out.replace(/\u0000CMTOPEN\u0000/g, '<!--').replace(/\u0000CMTCLOSE\u0000/g, '-->');
  out = out.replace(/\u0000AUTOLINK(\d+)\u0000/g, (m, i) => autolinks[Number(i)]);
  out = out.replace(/\u0000FENCE(\d+)\u0000/g, (m, i) => fenceBlocks[Number(i)]);

  return out;
}

function fixLinks(text) {
  return text.replace(/\]\((?!https?:\/\/)([^)\s]+\.md[^)\s]*)\)/g, (match, p1) => {
    const clean = p1.replace(/^\.?\//, '');
    return `](${GITHUB_BASE}${clean})`;
  });
}

function sanitize(text) {
  return fixLinks(mdxSafe(text));
}

function firstLine(text, maxLen) {
  const clean = text.replace(/^#.*\n+/, '').trim().split('\n')[0] || '';
  return clean.length > maxLen ? clean.slice(0, maxLen - 1) + '…' : clean;
}

function writeDoc(filename, title, description, body, subfolder) {
  const safeDesc = (description || '').replace(/"/g, "'").slice(0, 140);
  const frontmatter = `---\ntitle: "${title}"\ndescription: "${safeDesc}"\n---\n\n`;
  const note = `{/* Auto-generated by scripts/generate-docs-mintlify.js dari file sumber repo. Edit sumbernya, lalu jalankan generator ulang. */}\n\n`;
  const safeBody = sanitize(body.trim());
  const outDir = subfolder ? path.join(DOCS_OUT, subfolder) : DOCS_OUT;
  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, filename), frontmatter + note + safeBody + '\n');
  console.log(`  ok ${subfolder ? subfolder + '/' : ''}${filename}`);
}

function extractSection(content, headingRegex) {
  if (!content) return null;
  const lines = content.split('\n');
  const startIdx = lines.findIndex((l) => headingRegex.test(l));
  if (startIdx === -1) return null;
  let endIdx = lines.length;
  const headingLevel = (lines[startIdx].match(/^#+/) || ['#'])[0].length;
  for (let i = startIdx + 1; i < lines.length; i++) {
    const m = lines[i].match(/^(#+)\s/);
    if (m && m[1].length <= headingLevel) {
      endIdx = i;
      break;
    }
  }
  return lines.slice(startIdx, endIdx).join('\n').trim();
}

