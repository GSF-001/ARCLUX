if (!fs.existsSync(DOCS_OUT) || !fs.existsSync(path.join(DOCS_OUT, 'docs.json'))) {
  console.error('ERROR: docs-site/docs.json belum ada. Jalankan 01-reset-and-scaffold-mintlify.sh dulu.');
  process.exit(1);
}

const readme = readIfExists('README.md');
const context = readIfExists('CONTEXT.md');

{
  let body = '';
  if (readme) {
    const cut = readme.search(/^#+\s*(Installation|Usage|Getting Started|Quickstart)/im);
    body += stripFrontmatter(cut > -1 ? readme.slice(0, cut) : readme);
  }
  if (context) body += `\n\n## Context tambahan\n\n${stripFrontmatter(context)}`;
  if (!body.trim()) body = '_README.md tidak ditemukan di root repo._';
  writeDoc('intro.mdx', 'Intro', firstLine(body, 140) || 'Ringkasan project ARCLUX', body);
}

{
  let body = '';
  const quickstart = readIfExists('QUICKSTART.md');
  if (quickstart) body += stripFrontmatter(quickstart);
  if (readme) {
    const installSection = extractSection(readme, /^#+\s*(Installation|Getting Started)/im);
    const usageSection = extractSection(readme, /^#+\s*(Usage|CLI|Commands)/im);
    if (installSection) body += `\n\n${installSection}`;
    if (usageSection) body += `\n\n${usageSection}`;
  }
  if (!body.trim()) body = '_Tidak ditemukan bagian instalasi/usage di README.md atau QUICKSTART.md._';
  writeDoc('usage.mdx', 'Instalasi & Penggunaan', 'Cara install dan pakai ARCLUX', body);
}

{
  const arch = readIfExists('ARCHITECTURE_MAP.md');
  const body = arch ? stripFrontmatter(arch) : '_ARCHITECTURE_MAP.md tidak ditemukan di root repo._';
  writeDoc('architecture.mdx', 'Arsitektur', 'Peta struktur & boundary codebase ARCLUX', body);
}

{
  let body = '';
  const tooling = readIfExists('TOOLING.md');
  if (tooling) body += stripFrontmatter(tooling);
  const pkgJson = readIfExists('package.json');
  if (pkgJson) {
    try {
      const pkg = JSON.parse(pkgJson);
      if (pkg.workspaces) {
        body += `\n\n## Workspaces\n\n`;
        const ws = Array.isArray(pkg.workspaces) ? pkg.workspaces : pkg.workspaces.packages || [];
        ws.forEach((w) => (body += `- \`${w}\`\n`));
      }
    } catch (e) {}
  }
  if (!body.trim()) body = '_TOOLING.md tidak ditemukan._';
  writeDoc('stack.mdx', 'Stack & Environment', 'Tooling dan environment yang dipakai ARCLUX', body);
}

{
  const progres = readIfExists('PROGRES.md');
  const body = progres ? stripFrontmatter(progres) : '_PROGRES.md tidak ditemukan di root repo._';
  writeDoc('status.mdx', 'Status & Progress', 'Progress terkini, bug terbuka, prioritas', body);
}

{
  let body = '';
  if (context) {
    const gotchaSection = extractSection(context, /^#+\s*(Gotcha|Known Issues|Catatan)/im);
    if (gotchaSection) body += gotchaSection;
  }
  if (!body.trim()) {
    body =
      '_Belum ada bagian "Gotchas"/"Known Issues" terdeteksi otomatis di CONTEXT.md. ' +
      'Tambahkan section dengan heading `## Gotchas` di CONTEXT.md, atau edit file ini manual._';
  }
  writeDoc('gotchas.mdx', 'Gotchas', 'Hal-hal yang gampang bikin salah kalau gak tau', body);
}

// Detail progress files (progres/*.md) — masing-masing jadi halaman terpisah
{
  const progresDir = path.join(ROOT, 'progres');
  if (fs.existsSync(progresDir)) {
    const files = fs.readdirSync(progresDir).filter((f) => f.endsWith('.md'));
    const pages = [];
    files.forEach((f) => {
      const content = fs.readFileSync(path.join(progresDir, f), 'utf-8');
      const slug = f.replace(/\.md$/, '').toLowerCase().replace(/[^a-z0-9]+/g, '-');
      const filename = `progres-${slug}.mdx`;
      const title = f.replace(/\.md$/, '').replace(/[-_]/g, ' ');
      writeDoc(filename, title, `Detail progres: ${title}`, stripFrontmatter(content), 'progres');
      pages.push(filename.replace('.mdx', ''));
    });
    if (pages.length) console.log(`  info progres pages: ${pages.join(', ')} -- tambahkan ke docs.json nav`);
  }
}

// Codebase Map — 1 halaman per package/app, dari package.json + export list
{
  function scanExports(dir) {
    const candidates = ['index.ts', 'index.tsx', 'index.js', 'src/index.ts', 'src/index.tsx', 'src/index.js'];
    for (const c of candidates) {
      const p = path.join(dir, c);
      if (fs.existsSync(p)) {
        const src = fs.readFileSync(p, 'utf-8');
        const names = new Set();
        let m;
        const reNamed = /export\s+(?:const|function|class|interface|type|enum)\s+([A-Za-z0-9_]+)/g;
        while ((m = reNamed.exec(src))) names.add(m[1]);
        const reBrace = /export\s*\{([^}]+)\}/g;
        while ((m = reBrace.exec(src))) {
          m[1].split(',').forEach((n) => {
            const clean = n.trim().split(/\s+as\s+/)[0].trim();
            if (clean) names.add(clean);
          });
        }
        const reReExport = /export\s*\*\s*from\s*['"]([^'"]+)['"]/g;
        const reExports = [];
        while ((m = reReExport.exec(src))) reExports.push(m[1]);
        const hasDefault = /export\s+default\s+/.test(src);
        return { file: c, exports: [...names], reExports, hasDefault };
      }
    }
    return null;
  }

  function findPackageReadme(dir) {
    const candidates = ['README.md', 'readme.md'];
    for (const c of candidates) {
      const p = path.join(dir, c);
      if (fs.existsSync(p)) return fs.readFileSync(p, 'utf-8').trim();
    }
    return null;
  }

  function scanGroup(groupDir, label) {
    const base = path.join(ROOT, groupDir);
    if (!fs.existsSync(base)) return [];
    const entries = fs.readdirSync(base).filter((f) => fs.statSync(path.join(base, f)).isDirectory());
    const pageNames = [];
    entries.forEach((name) => {
      const dir = path.join(base, name);
      const pkgPath = path.join(dir, 'package.json');
      let pkgName = name;
      let description = '';
      if (fs.existsSync(pkgPath)) {
        try {
          const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
          pkgName = pkg.name || name;
          description = pkg.description || '';
        } catch (e) {}
      }
      const exp = scanExports(dir);
      const hasPkgJson = fs.existsSync(pkgPath);
      let body = `## ${groupDir}/${name}\n\n`;
      if (description) {
        body += `${description}\n\n`;
      } else {
        const pkgReadme = findPackageReadme(dir);
        if (pkgReadme) {
          body += `${pkgReadme}\n\n`;
        } else if (!hasPkgJson) {
          body += `_Tidak ada package.json (bukan package standar Node)._\n\n`;
        } else {
          body += '_Belum ada deskripsi di package.json atau README.md._\n\n';
        }
      }
      if (!exp) {
        const entries = fs.readdirSync(dir).filter((f) => !f.startsWith('.'));
        if (entries.length) {
          body += `**Isi folder:**\n\n`;
          entries.forEach((e) => {
            const isDir = fs.statSync(path.join(dir, e)).isDirectory();
            body += `- \`${e}\`${isDir ? '/' : ''}\n`;
          });
          body += `\n`;
        }
      }
      if (exp && (exp.exports.length || exp.reExports.length || exp.hasDefault)) {
        body += `**Exports** (dari \`${exp.file}\`):\n\n`;
        exp.exports.forEach((e) => (body += `- \`${e}\`\n`));
        exp.reExports.forEach((r) => (body += `- re-exports from \`${r}\`\n`));
        if (exp.hasDefault) body += `- \`default\` export\n`;
      } else if (exp) {
        body += `_Entry point \`${exp.file}\` ditemukan, tapi tidak ada export terdeteksi._\n`;
      } else {
        body += `_Tidak ada file entry point (index.ts/js) ditemukan._\n`;
      }
      const slug = `map-${groupDir}-${name}`.toLowerCase().replace(/[^a-z0-9]+/g, '-');
      const filename = `${slug}.mdx`;
      writeDoc(filename, `${groupDir}/${name}`, description || `Ringkasan ${groupDir}/${name}`, body, 'map');
      pageNames.push(filename.replace('.mdx', ''));
    });
    return pageNames;
  }

  const mapPages = [...scanGroup('packages', 'packages'), ...scanGroup('apps', 'apps')];
  if (mapPages.length) console.log(`  info codebase map pages: ${mapPages.join(', ')} -- tambahkan ke docs.json nav`);
}

